// Si lo pones en true, las miniaturas se piden reducidas (400px, WebP) a través
// del servicio gratuito wsrv.nl. La foto completa solo se descarga al abrir el visor.
const USE_THUMBNAILS = false;
const THUMB_WIDTH = 400;

// ── No hace falta tocar nada de aquí hacia abajo ─────────────
const toUrl = (path) => (/^https?:\/\//.test(path) ? path : IMAGE_BASE + path);

const toThumb = (url) =>
  USE_THUMBNAILS
    ? `https://wsrv.nl/?url=${encodeURIComponent(url)}&w=${THUMB_WIDTH}&output=webp`
    : url;

const PHOTOS = Object.entries(GALLERY).flatMap(([category, items]) =>
  items.map((item, i) => {
    const entry = typeof item === 'string' ? { url: item } : item;
    const url = toUrl(entry.url);
    return {
      id: `${category}-${i}`,
      title: entry.title || category,
      category,
      url,
      thumb: toThumb(url),
    };
  })
);

export { toUrl };
export default PHOTOS;